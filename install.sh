#!/usr/bin/env bash
# synced-lyrics-linux — one-command install for CachyOS / Arch Linux.
# Repo: https://github.com/konn-neko/synced-lyrics-linux
#
# Run this yourself (it uses sudo for pacman, so it never runs unattended):
#   ./install.sh
#
# What it does:
#   1. Installs python-pyside6 from the Arch/CachyOS repos (or, if pacman
#      is not available, creates a venv and pip-installs PySide6).
#   2. Installs playerctl (optional, MPRIS fallback) if pacman is present.
#   3. Creates ~/.local/bin/synced-lyrics launcher.
#   4. Creates ~/.local/share/applications/synced-lyrics-linux.desktop
#      so the app shows up in the KDE application launcher.
# It does NOT start the app, touch your music players, or need any login.
set -euo pipefail
cd "$(dirname "$0")"

APP_DIR="$(pwd)"
LAUNCHER="$HOME/.local/bin/synced-lyrics"
DESKTOP_FILE="$HOME/.local/share/applications/synced-lyrics-linux.desktop"

echo "== synced-lyrics-linux installer =="
echo "App directory: $APP_DIR"

if command -v pacman >/dev/null 2>&1; then
    echo "-- Installing python-pyside6 + playerctl via pacman (sudo) --"
    sudo pacman -S --needed --noconfirm python-pyside6 playerctl
    PYTHON=python3
elif command -v apt-get >/dev/null 2>&1; then
    echo "-- Installing python3-pyside6 via apt (sudo) --"
    sudo apt-get update
    sudo apt-get install -y python3-pyside6 playerctl
    PYTHON=python3
elif command -v dnf >/dev/null 2>&1; then
    echo "-- Installing python3-pyside6 via dnf (sudo) --"
    sudo dnf install -y python3-pyside6 playerctl
    PYTHON=python3
else
    echo "-- No system package manager found; creating a venv --"
    python3 -m venv "$APP_DIR/.venv"
    "$APP_DIR/.venv/bin/pip" install -r "$APP_DIR/requirements.txt"
    PYTHON="$APP_DIR/.venv/bin/python"
fi

mkdir -p "$HOME/.local/bin" "$HOME/.local/share/applications"

cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# synced-lyrics-linux launcher (generated by install.sh)
exec $PYTHON "$APP_DIR/synced_lyrics.py" "\$@"
EOF
chmod +x "$LAUNCHER"

cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=Synced Lyrics
Comment=Native Linux synced lyrics (MPRIS + LRCLIB)
Exec=$LAUNCHER
Icon=audio-x-generic
Terminal=false
Categories=AudioVideo;Audio;Player;
StartupWMClass=synced-lyrics-linux
EOF

echo
echo "Done."
echo "  Run:   synced-lyrics            (or: synced-lyrics --mode overlay)"
echo "  Demo:  synced-lyrics --demo"
echo "  Or launch 'Synced Lyrics' from the KDE application launcher."
echo "  Play something in Spotify or YouTube Music and the lyrics follow."
